package devtools;

import java.awt.image.BufferedImage;

/**
 * 被驱动者：trace 导出器与被导出的面板之间那条**面板无关**的缝。
 *
 * 只有三件事：推进一步 / 快照可断言状态 / 快照这一步之后真的画出来的位图。
 * 导出器（{@link ExportTrace}）只通过这三件事工作 —— 它不认识 ScenePanel，
 * 也不认识任何别的面板；确定性、剧本、定时器怎么虚拟化，全归实现方管。
 *
 * 为什么要有它：原版另有战斗 / 菜单 / 商店三个面板各自成体系，而真值设施
 * （逐步导出、两遍确定性校验、帧清单、跨端比对接线）只有一套。每接一个面板
 * 就复制一遍导出器，等于把"两遍导出逐字节一致"这件唯一让真值可信的事
 * 复制成四份各自演化的实现。
 *
 * "一步"由实现方定义：tick 驱动的场景面板一步 = 一个 tick；事件驱动的菜单
 * 与商店一步 = 一次输入事件。Web 侧 replay 的 seek 本来就是这个形状。
 *
 * 目前唯一的实现是 {@link SceneDriver}。这是有意的 —— 这条缝是先抽出来、
 * 由五份已验收的场景真值逐字节不变来证明它没改变任何行为，然后别的面板才接上来。
 */
public interface TraceDriver {

    /**
     * 推进一步，并把这一步真的画出来。
     *
     * @return true = 这一步产出了一条真值记录（导出器接着取快照）；
     *         false = 剧本已经跑完，本次调用没有产出任何东西。
     *         跑不完（超预算、走不到、按了空格没搭上话）一律是硬失败，
     *         由实现方直接终止进程 —— 绝不能靠返回 false 蒙混成"正常结束"。
     */
    boolean step();

    /**
     * 快照上一次 {@link #step()} 之后的可断言状态，返回一个 JSON 对象。
     *
     * @param index 这是第几步，从 0 起。导出器给号，实现方不自己数。
     */
    String snapshotState(int index);

    /**
     * 快照上一次 {@link #step()} 之后**真的画出来的**那张位图。
     *
     * 实现方负责校验它确实是自己那个面板该有的样子（类型、尺寸），校验不过
     * 是硬失败：一张尺寸不对却照样能编码成 PNG 的图，失败起来和成功一模一样。
     */
    BufferedImage snapshotImage();
}
