/**
 * 文字层的字体：唯一的一处定义（xl-9bd.17 的裁定）。
 *
 * ## 原版写的是什么，实际画出来的是什么
 *
 * 原版 22 处 `setFont` 里有 18 处写死 `new Font("文鼎粗钢笔行楷", Font.BOLD, n)`
 * （另有 `宋体` 与 `正楷` 各若干）。这三款都**没有随游戏交付** —— `image/`、
 * `sources/`、`jl1.0.jar` 里没有任何字体文件。所以"原版的字形"从来就不是一个
 * 确定的东西：十三年前装了文鼎的机器上是行楷，没装的退到 Java 的默认字体。
 *
 * 票要求"有人拿眼睛看一眼"。看过了，而且先量了。**在跨端比对的基准机上
 * （macOS 15 / openjdk 17.0.20.1）实测**：
 *
 * ```java
 * new Font("文鼎粗钢笔行楷", Font.BOLD, 20).getFamily()  // -> "Dialog"
 * ```
 *
 * 三个名字（文鼎粗钢笔行楷 / 宋体 / 正楷）以及一个随手编的不存在的名字，
 * 拿同一句中文各画一张 400×40 的位图，四张**逐像素完全相同**。也就是说
 * 基准侧根本没有走到行楷，走的是逻辑字体 `Dialog`。再把 `Dialog` 与本机
 * 13 款候选物理字体逐像素比：`PingFang SC`、`Helvetica`、`Lucida Grande`
 * 三个与 `Dialog` 完全相同（中文段共用同一条 CoreText 回退），`STKaiti`、
 * `Kaiti SC`、`Songti SC`、`Heiti SC` 等全部不同。
 *
 * **结论：比对基准里的中文字形是 PingFang SC 那样的现代无衬线，不是行楷。**
 *
 * ## 裁定：不打包字体
 *
 * 三条理由，按分量排：
 *
 * 1. **打包行楷会让 web 端离基准更远，不是更近。** 基准画的是无衬线；给
 *    web 塞一款行楷（比如 OFL 的霞鹜文楷）等于让两端的字形从"都退到无衬线"
 *    变成"一边行楷一边无衬线"，比对只会更红。要"忠于作者意图"就得连基准侧
 *    一起换字体，那是改原版——迁移期明令不做（见 CLAUDE.md）。
 * 2. **打包解决不了逐像素。** Java2D 与浏览器的栅格化、hinting、基线摆位
 *    本来就不是一回事：`ui/dialogueLayout.ts` 里的 `BASELINE_TO_TOP` 就是
 *    这条缝的近似补偿。即便两端加载同一个 ttf，文字那几块也收敛不到 0。
 *    换句话说，字体不是这笔账的最后一块，打包只是换一种偏离。
 * 3. **省下一个许可问题与几百 KB 的首屏。**
 *
 * 落地的动作因此不是"加字体"，而是**把 web 的后备链改成与基准同一个落点**：
 * 原来那条 `"文鼎粗钢笔行楷", "STKaiti", "KaiTi", serif` 头一个名字在任何
 * 机器上都不会命中，实际生效的是 `STKaiti` —— 一款楷体，与基准的无衬线是
 * 两种字形，这是我们自己引进来的偏差，不是原版的。
 *
 * ## 换完之后量到了什么
 *
 * 三条链各跑一遍 `tools/compare-frames.sh dorm-intro --every 25`
 * （165 帧，容差 8）。原版侧那 165 张位图三次完全相同，只有 web 侧重截：
 *
 * | 字体链 | 差异像素合计 | 占比 | 最差帧 t=800 |
 * |---|---|---|---|
 * | `'文鼎粗钢笔行楷','STKaiti','KaiTi',serif`（改前） | 1126591 | 1.0418% | 5.5397% |
 * | 本机默认无衬线（现在这条） | 992667 | 0.9180% | 5.6325% |
 * | 钉死 `'PingFang SC',system-ui,sans-serif` | 992501 | 0.9178% | 5.6310% |
 *
 * `tools/compare-frames.sh dorm-walk --every 100`（6 帧，对话框那条路径）
 * 的最差帧 #500 同时从 1.0056% 降到 0.7401%。
 *
 * **总量降了 11.9%，最差帧反而涨了 0.09 个百分点**，两个方向都要说清楚：
 * 字形对上以后差异的**面积**明显缩了，但浏览器把粗体画得比 Java2D 重
 * （同一行旁白，亮度 > 220 的像素 java 2508 个 / web 3017 个），字最多的
 * 那一帧因此在笔画边缘多亏一点。挑"总量"而不是"最差帧"当判据的理由是前者
 * 覆盖全部 165 帧、后者只是其中一帧的一个数。
 *
 * 还有一笔字体换不掉：同一行文字 web 比 java 宽 —— 第一行 19 个字 java 的
 * 墨迹到 x=426、web 到 x=433，第二行 43 个字 java 到 908、web 到 924，
 * 都是每字约 0.37 px 的累积。原版 `FontMetrics` 给的中文步进是整 20 px
 * （字号），浏览器不是。要消掉它得像对话框那样**逐字按格摆**，那是排版不是
 * 字体，不在这张票里。
 *
 * ## 为什么写"规则"而不写一个字体名
 *
 * 这条链刻意**不钉死 `PingFang SC`**：上表里钉死与不钉死只差 166 个像素
 * （0.0002 个百分点），而基准侧 Java 的 `Dialog` 本身就是"本机的默认字体"
 * 这条规则，在别的机器上落到别的字。两端各自照同一条规则回退，才是换台机器
 * 也成立的做法；钉死一个 macOS 的字体名，只在这台机器上对。
 *
 * 剩下的偏离是**已知缺口**，判据、数字与包围盒记在 `compare/expected.ts`
 * 的 dorm-intro / dorm-walk 两条里。换字体没有动到那 8 帧"不超容差"的帧
 * （t=1425、1750、1925、2050、2950、3075、3175、3950）—— 三条链下这 8 帧
 * 是同一组，因为它们一个字都没画。
 *
 * ## 一处定义
 *
 * CSS 侧（对话框的名字与正文）用 `index.css` 里的 `--xl-text-font`，
 * Canvas 侧（旁白）用这里的 `TEXT_FONT_STACK`。两处必须一模一样，
 * `textFont.test.ts` 直接读 `index.css` 断言这一点 —— 只改一处会响。
 */
export const TEXT_FONT_STACK =
  "system-ui, -apple-system, 'PingFang SC', 'Microsoft YaHei', sans-serif"

/** `index.css` 里承载同一份字体链的自定义属性名。 */
export const TEXT_FONT_CSS_VAR = '--xl-text-font'
