/**
 * 假货的**声明标记**。
 *
 * 迁移期里，上游做完了而下游那个里程碑还没开始，web 端就得用一个临时顶替物
 * 让上游先跑起来（`CONTEXT.md` §假货）。问题不是假货本身，是
 * **一个被忘掉的假货和一个正常工作的真货长得一样**（ADR-0005）：真的那一份
 * 做出来的那天没人会记得这里还挂着一个假的，于是两套并存，而两套并存的样子
 * 与一套正常工作的样子完全相同。
 *
 * 所以每一样假货都要做两件事：
 *
 * 1. 在自己的模块里调一次 `declareFake('<id>')` —— 这是**代码侧**的标记，
 *    磁盘上扫得到；
 * 2. 在 `registry.ts` 的 `REGISTERED_FAKES` 里写一行 —— 这是**登记册**，
 *    由人来签，写明归哪张票、真的那一份长什么样。
 *
 * 两边**对撞**，`registry.test.ts` 两个方向都会红：
 *
 * - 册子里有、磁盘上扫不到（代码已经变成真货了，或者假货被挪走了）→ 红；
 * - 磁盘上扫得到、册子里没有（有人删了登记，代码还是假的）→ 红。
 *
 * 这个形状不是新发明的，抄的是 `battleTrace.test.ts` 里
 * `IMPLEMENTED` / `BATTLE_TRACE_NAMES` 那一对（ADR-0005 §Consequences）。
 */
export type FakeId = string

/**
 * 声明"这个模块是假货"。返回值只是把 id 原样递出来，方便模块导出去给人看；
 * **真正起作用的是这个调用在源码里留下的字面量** —— `registry.test.ts` 扫的
 * 就是它。所以 id 必须写成**字面量**，不许是变量或模板串（扫描器解不出变量，
 * 而"解不出"与"没有假货"长得一样，那条用例的第一段断言正是拦这个的）。
 */
export function declareFake(id: FakeId): FakeId {
  return id
}
