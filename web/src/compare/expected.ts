/**
 * 每条剧本在**当前这个移植进度下**应该是什么结果。
 *
 * 为什么需要这张表：Web 版还没做对话框、素材重编码还差一层，跨端比对现在
 * 必然红。
 * 一条"现在肯定红"的流水线不会有人看，第二天就变成噪声；而把阈值放松到能过，
 * 就变成了这个项目最贵的那种检查 —— 通过条件是"没找到问题"。
 *
 * 所以这里显式声明每条剧本的预期，**两头都会红**（`src/assets/knownMissing.ts`
 * 是同一个套路）：
 *
 * - `match` 的剧本出现偏离帧 → 红，报告指出第一个偏离的帧号；
 * - `gap` 的剧本一帧都不偏了 → **也红**，因为那说明缺口补上了，这张表过期了。
 *
 * 否则"缺口还在"与"表早就该改了"看起来会一模一样。
 *
 * **每笔账都有上界**（xl-l3o）。上面那两条只管"有没有偏离"，不管偏了多少 ——
 * 于是渲染整个崩掉也照样绿。实测（2026-09-06）：把基准侧 `snapshotImage()` 换成
 * 一张全黑的 1024×640，`dorm-walk` 的最差帧从 0.7401% 跳到 99.9565%，
 * `tools/compare-frames.sh` 退出 0、报"1/1 条剧本符合预期"。所以整屏表态要写
 * `maxRatio`（每帧的占比上界），分区表态要给每个缺口区写 `maxPixels`
 * （每帧的像素数上界）。
 *
 * **余量为什么是 2 倍。** 上界要挡住"什么都没画出来"，又不能让另一台机器的正常
 * 抖动变红。这条流水线上最会抖的东西是**后备字体**：两端都退到各自的后备链，
 * 同一帧的差异会跟着链子走。本仓库记录的实测（xl-9bd.17 / xl-9bd.18 的注释，
 * 数字是当时量的、不是这次）里，`dorm-intro` 最会写字的那一帧 t=800 在
 * **5.5397% → 5.6325% → 2.8482%** 之间来回，最宽的一档是 1.98 倍；这一次重量
 * 到的正是 2.8482%，与记录里改完之后的那个数一致。所以取 **2 倍**：它盖得住
 * "这台机器挑了另一条后备链"，而盖不住"这一帧没画出来"（全黑 ≈ 100%，比任何
 * 一条剧本的上界都高出一截）。
 *
 * 重编码那几条（大地图的有损 WebP）其实比字形稳得多 —— 两端的解码器都是定死的
 * —— 2 倍对它们是宽的；这里仍然用同一条规则，宁可规则统一、余量说得清，也不要
 * 每条剧本各拍一个数。
 */
export interface Expectation {
  /**
   * - `match` —— 两端逐像素相等。
   * - `gap`   —— **比过了**，剩一笔说得清、有上界的账。
   * - `unassembled` —— **一帧都还没比过**：取图页装配不出这个驱动器，整条
   *   流水线在这条剧本上非零退出（见 `replay/drivers.ts`）。它不是 `gap`：
   *   `gap` 的每一个数都该是量出来的，而这种剧本一个像素都没画过，写任何
   *   上界都是编的。web 侧把那个面板做出来之后，这一条要么变 `match`、
   *   要么带上真量出来的 `maxRatio` / `gaps` 变成 `gap`。
   *
   * 这个取值是 xl-1vu.4 与 xl-1vu.5 合流时定的：两张票各自都写了
   * `status: 'gap'` 且刻意不写上界（理由都对——没量过），而 xl-l3o 同时立了
   * 「每条 gap 都必须有上界」。三者都对，说明缺的是一个状态，不是一个数。
   *
   * - `unpainted` —— **驱动器装得出，可这条剧本会走进一层还没实现的绘制**，
   *   `battleDrawList` 当场抛（xl-rh9.11）。同样一帧都没比过，所以同样不许带
   *   任何量出来的数。
   *
   *   为什么它不能并进 `unassembled`：那一个说的是「整个面板还没做」，由
   *   `replay/implemented.ts` 那份**驱动器**名单裁决，而这一个是同一个面板里
   *   某几层还没画。两者归的票不是一张，而且 `unassembled.ts` 的双向对撞是
   *   拿驱动器名单撞的 —— 把 `battle` 从那份名单里摘掉，五条已经在比的战斗
   *   剧本会一起哑掉。
   *
   *   它也不是一个逃生舱：`drawList.test.ts` 里那条「unpainted 的剧本必须真的
   *   抛，而且抛的那句话点的正是它挂的那张票」会把它撞回来。哪天那几层画出来
   *   了，那条判据先红。
   */
  readonly status: 'match' | 'gap' | 'unassembled' | 'unpainted'
  /** `gap` / `unassembled` / `unpainted` 必须说清楚差在哪／为什么比不了、归哪张票。`match` 不写。 */
  readonly why?: string
  readonly issue?: string
  /**
   * **幅度上界**（xl-l3o）：每一帧的差异占比都必须 ≤ 这个数。
   *
   * 整屏表态的 `gap` 必须写它（写了 `gaps` 的分区表态不用 —— 那边的上界逐区
   * 挂在 `GapRegion.maxPixels` 上，且缺口区之外一个像素都不许差）。没有上界
   * 时通过条件只剩一句"有偏离帧"，于是**渲染整个崩掉也照样绿**：实测把基准侧
   * `snapshotImage()` 换成全黑图，最差帧从 0.7401% 跳到 99.9565%，流水线退出 0。
   *
   * 取值一律**实测**：跑一遍 `tools/compare-frames.sh`，读报告里那条剧本的
   * 最差帧占比，再按下面每条剧本注释里写明的余量放大。判据与"为什么是每帧
   * 不是所有帧之和"在 `verdict.ts`。
   */
  readonly maxRatio?: number
  /**
   * **分区表态**（xl-1vu.3）。写了它，这条剧本就换一套更硬的判据（判据本身在
   * `regions.ts`，这里只放表）：
   *
   * - 列出来的矩形是**缺口区**，照旧记账，且**每个区各自双向红** —— 某个区
   *   一帧都不差了，就是那笔账还完了而表没改；
   * - 矩形**之外**全是**硬比区**，每一个像素都必须在容差内相等。不是"超过
   *   阈值才算偏"，是**一个都不许有**。
   *
   * 为什么值得多写这几行：不写分区时，"这条剧本红着"这件事本身没有分辨力 ——
   * 缺口挪到了别的地方、多长出一块新的偏离，`status: gap` 照样通过。写了分区，
   * 偏离多出一个像素落在没人声明过的地方就会红。
   *
   * 缺口区**不许互相重叠**，也不许把整屏铺满（那就该老老实实写 `status: match`）。
   */
  readonly gaps?: readonly GapRegion[]
}

